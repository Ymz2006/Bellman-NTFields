"""Near-wall slope and direction of the trained fields (report/wallfeel.md, wallfeel.json): the mechanism behind the
segment-DP chains' extra collisions.

    CUDA_VISIBLE_DEVICES=0 ~/.venvs/bellman-ntfield/bin/python jeffrey/maze_scale/wallfeel.py

On the 50,000 held-out ntrl-demo pairs of each maze (x0 within the margin of a wall, x1 anywhere): at near-wall x0
(trained speed S < 0.3), the median of S |grad_x0 T(x0, x1)| (ntrl-demo's eikonal target 1) and of the cosine between
grad_x0 T and -n (n = unit gradient of the clearance; ntrl-demo's normal label asks S grad T = -n: the field rises into
the wall), by the pair's gap in cells. Inference only, training seed 87358 runs.
"""
import json
import sys
from pathlib import Path
import numpy as np
import torch

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import maze as MZ  # noqa: E402
import plan as P  # noqa: E402
import report as R  # noqa: E402
from fields import load_chain  # noqa: E402
from zoomfield import load_zoomed  # noqa: E402

GAPS = [(0, 0.5), (0.5, 2), (2, 8), (8, 1e9)]


def measure(maze, prepared, grad):
    hx = torch.tensor(np.load(prepared / 'heldout/sampled_points.npy'), device=maze.device)
    hd = torch.tensor(np.load(prepared / 'heldout/clearance_cells.npy'), device=maze.device)[:, 0]
    _, normal = maze.clearance_normal(hx[:, :3])
    S = maze.train_speed(hd)
    gap = torch.linalg.vector_norm(hx[:, :3] - hx[:, 3:], dim=1) / maze.pitch
    _, g = grad(hx)
    slope = S * torch.linalg.vector_norm(g, dim=1)
    cos = torch.nn.functional.cosine_similarity(g, -normal, dim=1)
    out = {}
    for lo, hi in GAPS:
        near = (gap >= lo) & (gap < hi) & (S < 0.3)
        if int(near.sum()) > 20:
            out[f'{lo:g}-{hi:g}' if hi < 1e8 else f'>{lo:g}'] = dict(n=int(near.sum()), slope=float(slope[near].median()), cos=float(cos[near].median()))
    return out


def main():
    prep, ntrl, seg = R.collect()
    seed = 87358
    rows, res = [], {}
    fields = []
    for n in sorted(prep):
        if seed in ntrl.get(n, {}):
            fields.append((n, 'ntrl-demo', lambda n=n: (lambda net: (lambda x: P.field_grad(net, x)))(P.load_field(ntrl[n][seed]['_dir'] / 'training/checkpoint.pt'))))
        for v, by_n in seg.items():
            d = by_n.get(n, {}).get(seed)
            if d is None:
                continue
            if 'zoom' in d.get('config', {}):
                continue                      # zoomed-base chains are loaded by segdp2 conventions; skipped here
            fields.append((n, R.short_variant(d), lambda d=d: (lambda ch: ch.cost_grad)(load_chain(d['_dir'] / 'chain/field.pt')[0])))
    for d in R.runs('zoom'):
        if d['seed'] == seed:
            fields.append((d['maze']['n'], f'zoom x{d["zoom"]:.2f}', lambda d=d: (lambda net: (lambda x: P.field_grad(net, x)))(load_zoomed(d['_dir'] / 'training/checkpoint.pt', d['zoom']))))
    for n, name, make in sorted(fields, key=lambda t: (t[0], t[1])):
        maze = MZ.Maze(n)
        m = measure(maze, prep[n]['_dir'], make())
        res[f'{n}|{name}'] = m
        rows.append(f'| {n} | {name} | ' + ' | '.join(f'{m[k]["slope"]:.2f} / {m[k]["cos"]:.2f}' if k in m else '-' for k in [f'{lo:g}-{hi:g}' if hi < 1e8 else f'>{lo:g}' for lo, hi in GAPS]) + ' |')
        torch.cuda.empty_cache()
    head = ['# Near-wall slope / direction (generated by wallfeel.py)', '',
            'Held-out pairs with near-wall x0 (S < 0.3): median S |grad_x0 T| (eikonal target 1) / median cos(grad_x0 T, -n), by gap in cells; training seed 87358.', '',
            '| maze | field | ' + ' | '.join(f'{lo:g}-{hi:g}' if hi < 1e8 else f'>{lo:g}' for lo, hi in GAPS) + ' |', '|' + '---|' * (len(GAPS) + 2)]
    (R.OUT / 'wallfeel.md').write_text('\n'.join(head + rows) + '\n')
    (R.OUT / 'wallfeel.json').write_text(json.dumps(res, indent=1))
    print('\n'.join(head + rows))


if __name__ == '__main__':
    main()
