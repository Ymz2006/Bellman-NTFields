"""Post-hoc failure analysis of the registered maze-scale runs (planning seed 0 paths): report/posthoc.md + posthoc.json.

    CUDA_VISIBLE_DEVICES=0 ~/.venvs/bellman-ntfield/bin/python jeffrey/maze_scale/posthoc.py

Per run and distance bin: failures that touch a wall while driving (the goal the scorer appends to a run that never
converged is excluded), runs that stalled (never reached the goal), the xy distance driven before the first wall contact (cells)
and that distance over the query's true path length, and the start-to-first-contact share of failures whose first
contact is within one cell of the start. Plus success by Euclidean start-goal distance (same planning runs, all
planning seeds from rows.npz), to compare with the travel-distance bins.
"""
import json
import sys
from pathlib import Path
import numpy as np
import torch

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import maze as MZ  # noqa: E402
import plan as P  # noqa: E402
import report as R  # noqa: E402
from common import BINS, bin_labels  # noqa: E402

EUCLID = [0, 2, 4, 8, 16, 32, 64]


def first_contact(maze, path):
    """xy distance (cells) driven before the first configuration with negative clearance, or None."""
    p = torch.tensor(path, device=maze.device)
    dense = P.densify(p, 0.005 * maze.pitch)
    d = maze.clearance(dense)
    bad = torch.nonzero(d < 0).squeeze(1)
    if not len(bad):
        return None
    seg = torch.linalg.vector_norm(dense[1:, :2] - dense[:-1, :2], dim=1)
    return float(seg[:int(bad[0])].sum() / maze.pitch)


def analyse(maze, prepared, run_dir):
    q = np.load(prepared / 'queries.npz')
    rows = np.load(run_dir / 'rows.npz')
    paths = np.load(run_dir / 'paths_seed0.npy', allow_pickle=True)
    out = dict(by_bin={}, by_euclid={})
    labels = bin_labels()
    contact = np.full(len(paths), np.nan)
    hit = np.zeros(len(paths), bool)                  # failed runs that touch a wall on the driven trajectory
    for i, p in enumerate(paths):
        if not rows['success'][0, i]:
            driven = p if rows['converged'][0, i] else p[:-1]   # the scorer appends the goal; a stalled run never drove that segment
            c = first_contact(maze, driven) if len(driven) > 1 else None
            if c is not None:
                contact[i], hit[i] = c, True
    for b in sorted(set(q['bin'].tolist())):
        m = q['bin'] == b
        fail = m & ~rows['success'][0]
        col = fail & hit
        cc = contact[col]
        frac = cc / q['path_cells'][col]
        out['by_bin'][labels[b]] = dict(failures=int(fail.sum()), collisions=int(col.sum()), stalls_no_contact=int((fail & ~hit & ~rows['converged'][0]).sum()),
                                        stalled=int((fail & ~rows['converged'][0]).sum()),
                                        contact_cells_median=float(np.nanmedian(cc)) if np.isfinite(cc).any() else None,
                                        contact_over_path_median=float(np.nanmedian(frac)) if np.isfinite(frac).any() else None,
                                        contact_within_1_cell=int(np.sum(cc <= 1.0)))
    eb = np.digitize(q['euclid_cells'], EUCLID) - 1
    for b in sorted(set(eb.tolist())):
        m = eb == b
        lab = f'{EUCLID[b]}-{EUCLID[b + 1]}' if b + 1 < len(EUCLID) else f'>{EUCLID[b]}'
        out['by_euclid'][lab] = [int(rows['success'][:, m].sum()), int(rows['success'][:, m].size)]
    return out


def main():
    prep, ntrl, seg = R.collect()
    zoom = {}
    for d in R.runs('zoom'):
        zoom.setdefault(d['maze']['n'], {})[d['seed']] = d
    groups = dict(ntrl={n: {s: d for s, d in by.items()} for n, by in ntrl.items()}, zoom=zoom)
    for v, by_n in seg.items():
        groups['segdp ' + v] = by_n
    res, md = {}, ['# Post-hoc failure analysis (planning seed 0 paths; generated by posthoc.py)', '']
    for name, by_n in groups.items():
        for n in sorted(by_n):
            maze = MZ.Maze(n)
            for s, d in sorted(by_n[n].items()):
                a = analyse(maze, prep[n]['_dir'], d['_dir'])
                res[f'{name}|{n}|{s}'] = a
                md.append(f'**{name}, {n} x {n}, training seed {s}** ({d["_id"]})')
                md.append('')
                md.append('| bin (cells) | failures | wall hit while driving | stalled (never reached the goal) | stalled without a wall hit | first contact after (cells, median) | ... as share of the true path | contact within 1 cell |')
                md.append('|---|---|---|---|---|---|---|---|')
                for lab, v in a['by_bin'].items():
                    f = lambda x, k='{:.2f}': '-' if x is None else k.format(x)
                    md.append(f'| {lab} | {v["failures"]} | {v["collisions"]} | {v["stalled"]} | {v["stalls_no_contact"]} | {f(v["contact_cells_median"])} | {f(v["contact_over_path_median"])} | {v["contact_within_1_cell"]} |')
                md.append('')
                md.append('Success by Euclidean distance (cells), all planning seeds: ' + ', '.join(f'{k}: {v[0]}/{v[1]}' for k, v in a['by_euclid'].items()))
                md.append('')
    (R.OUT / 'posthoc.md').write_text('\n'.join(md))
    (R.OUT / 'posthoc.json').write_text(json.dumps(res, indent=1))
    print('\n'.join(md[:60]))


if __name__ == '__main__':
    main()
