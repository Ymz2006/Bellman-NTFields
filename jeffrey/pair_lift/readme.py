"""README.md of the pair-lift study = README_setup.md + the findings page's text (report/pair_lift.html, charts and tables dropped) + report/tables.md.

    ~/.venvs/bellman-ntfield/bin/python jeffrey/pair_lift/readme.py [artifact url]
"""
import html
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def text_of(page):
    body = page[page.index('<div class="wrap">'):page.index('<div class="tip"')]
    body = re.sub(r'<details>.*?</details>', '', body, flags=re.S)
    body = re.sub(r'<div class="chart"[^>]*></div>', '', body)
    body = re.sub(r'<figure>.*?<figcaption>(.*?)</figcaption></figure>', r'<p>[figure: \1]</p>', body, flags=re.S)
    body = re.sub(r'<div class="math">(.*?)</div>', lambda m: '\n\n```\n' + m.group(1) + '\n```\n\n', body, flags=re.S)
    body = re.sub(r'<h1>(.*?)</h1>', r'\n\n### \1\n\n', body, flags=re.S)
    body = re.sub(r'<h2>(.*?)</h2>', r'\n\n### \1\n\n', body, flags=re.S)
    body = re.sub(r'<h3>(.*?)</h3>', r'\n\n#### \1\n\n', body, flags=re.S)
    body = re.sub(r'<div class="q">(.*?)</div>', r'\n\n**\1** ', body, flags=re.S)
    body = re.sub(r'<span class="verdict[^>]*>(.*?)</span>', r'[\1] ', body, flags=re.S)
    body = re.sub(r'</p>|</footer>|</header>', '\n\n', body)
    body = re.sub(r'<b>(.*?)</b>', r'**\1**', body, flags=re.S)
    body = re.sub(r'<code>(.*?)</code>', r'`\1`', body, flags=re.S)
    body = re.sub(r'<a href="([^"]*)">(.*?)</a>', r'\2 (\1)', body, flags=re.S)
    body = re.sub(r'<[^>]+>', '', body)
    body = html.unescape(body)
    out = []
    for para in re.split(r'\n\s*\n', body):
        para = para.strip('\n')
        if not para.strip():
            continue
        if para.lstrip().startswith('```') or '```' in para:
            out.append(para)
            continue
        words, line, lines = para.split(), '', []
        for w in words:
            if len(line) + len(w) + 1 > 138:
                lines.append(line)
                line = w
            else:
                line = (line + ' ' + w).strip()
        lines.append(line)
        out.append('\n'.join(lines))
    return '\n\n'.join(out)


def main():
    url = sys.argv[1] if len(sys.argv) > 1 else 'https://claude.ai/artifact/1Q3exN3woGsjQDvNC4NSow'
    setup = (HERE / 'README_setup.md').read_text().rstrip()
    page = (HERE / 'report/pair_lift.html').read_text()
    tables = (HERE / 'report/tables.md').read_text()
    tables = tables.replace('# pair_lift tables', '## Tables', 1).replace('\n## ', '\n### ')
    readme = (f'{setup}\n\n## Findings\n\nFindings page: {url} (`report/pair_lift.html`, built by `page.py`; the text below is the page\'s, generated by `readme.py`).\n\n'
              f'{text_of(page)}\n\n{tables}')
    (HERE / 'README.md').write_text(readme)
    print(f'{HERE / "README.md"}: {len(readme.splitlines())} lines')


if __name__ == '__main__':
    main()
