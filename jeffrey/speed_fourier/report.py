"""Tables for the speed-Fourier study from the registered runs: report/tables.md and report/summary.json.

    ~/.venvs/bellman-ntfield/bin/python jeffrey/speed_fourier/report.py

Success = MPPI successes over planning seeds 0/1/2. Fields: this study's speedfourier runs, and from earlier studies ntrl-demo (maze_scale ntrl stage) and
the grid-synced octaves (grid_sync gridsync stage) on the same mazes, queries, data and training seeds. Runs are paired by training seed where both exist.
"""
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / 'report'
PREPARED = {13: '20261101T192504Z-13cf1d04', 22: '20261101T193403Z-cea05796'}
SEEDS = [87358, 1, 2]


def field(d):
    if d['stage'] == 'ntrl':
        return 'ntrl-demo'
    if d['stage'] == 'gridsync':
        return d['mode']
    e = d['embedding']
    f, s, m, w = e['form'], e['scope'], e['terms'], e['walls']
    tgt = {'slow': ' slow', 'unit': ' unit'}.get(e.get('target', 'obstacle'), '')
    head = f" +head {e['head']}" + (f" w{e['head_fixed']:g}" if e.get('head_fixed') is not None else '') if e.get('head', 'none') != 'none' else ''
    if s in ('hits', 'depth', 'markint', 'markhits', 'intnorm'):                 # part 4 (rays.py)
        return f'{f} {s}' + (f" r{e['reach']:g}" if e.get('reach') else '') + (f" {e['norm']}" if e.get('norm') else '') + f' {w}' + (' unit' if e.get('target') == 'unit' else '') + head
    if s == 'integral' and m == 0:
        return f'{f} exact-integral {w}{tgt}{head}'
    if f == 'plain':
        return f"plain {e.get('rows_from', 'spectrum')}"
    if f in ('half', 'topzero'):
        return f
    if f in ('oracle', 'geo'):
        return f'{f} {w}'
    return f'{f} {s} M{m} {w}{tgt}' if s != 'map' else f'{f} map {w}{tgt}'


def runs():
    want = {str(ROOT / f'results/registered_{v}'): n for n, v in PREPARED.items()}
    out = []
    for r in sorted(ROOT.glob('results/registered_*/results.json')):
        try:
            d = json.loads(r.read_text())
        except Exception:
            continue
        if d.get('stage') not in ('ntrl', 'gridsync', 'speedfourier') or not d.get('complete') or d.get('smoke'):
            continue
        if str(Path(d.get('prepared', '')).resolve()) not in want or d.get('epochs') != 5000 or d.get('variant', 'metric') != 'metric':
            continue
        if d['stage'] == 'gridsync' and d['mode'] != 'octave':
            continue
        d['_n'], d['_id'], d['_dir'], d['_field'] = want[str(Path(d['prepared']).resolve())], r.parent.name.replace('registered_', ''), r.parent, field(d)
        out.append(d)
    return out


def row(d):
    ok, tot = d['success_total']
    q = np.load(Path(d['prepared']) / 'queries.npz')
    rows = np.load(d['_dir'] / 'rows.npz')
    err = np.abs(np.log(np.maximum(rows['t_pred'], 1e-9) / q['t_star']))
    return dict(id=d['_id'], ok=ok, tot=tot, success=ok / tot, collisions=sum(v['collision'] for v in d['planning'].values()), converged=sum(v['converged'] for v in d['planning'].values()) / tot, t_err=float(np.median(err)),
                speed_corr=d['speed_fit']['log_speed_corr'], spearman=d['field']['spearman'], t_ratio=d['field']['t_over_tstar_median'], descent=d['field']['descent_cos_median'],
                by_bin=d['success_by_bin'], fit=(d.get('embedding') or {}).get('fit'), head_weight=d.get('head_weight'))


def collect():
    t = {}
    for d in runs():
        t.setdefault(d['_n'], {}).setdefault(d['_field'], {})[d['seed']] = row(d)
    return t


def pooled(v, seeds=SEEDS):
    r = [v[s] for s in seeds if s in v]
    return sum(x['ok'] for x in r), sum(x['tot'] for x in r), len(r)


def paired(t, n, a, b):
    """Success of field a minus field b in points, for the training seeds both have (seeds 87358, 1, 2)."""
    A, B = t[n].get(a, {}), t[n].get(b, {})
    return [100 * (A[s]['success'] - B[s]['success']) for s in SEEDS if s in A and s in B]


def main():
    t = collect()
    names = sorted({f for n in t for f in t[n]})
    lines = ['# Speed-Fourier tables (generated by report.py)', '', 'Success over planning seeds 0/1/2, training seeds pooled (per seed in brackets, order 87358 / 1 / 2).', '',
             '| field | ' + ' | '.join(f'{n}×{n}' for n in t) + ' |', '|---|' + '---|' * len(t)]
    for f in names:
        cells = []
        for n in t:
            v = t[n].get(f)
            if not v:
                cells.append('–')
                continue
            ok, tot, k = pooled(v)
            cells.append(f'{100 * ok / tot:.1f} % ({k}) [' + ' / '.join(f'{v[s]["ok"]}' if s in v else '–' for s in SEEDS) + ']')
        lines.append(f'| {f} | ' + ' | '.join(cells) + ' |')
    lines += ['', '## Per run, training seed 87358', '', '| maze | field | success | collisions | median abs log T/T* | T/T* | Spearman | descent cos | log-speed corr | run |', '|---|---|---|---|---|---|---|---|---|---|']
    for n in t:
        for f in names:
            v = t[n].get(f, {}).get(87358)
            if v:
                lines.append(f'| {n} | {f} | {100 * v["success"]:.1f} % | {v["collisions"]} | {v["t_err"]:.3f} | {v["t_ratio"]:.2f} | {v["spearman"]:.3f} | {v["descent"]:.3f} | {v["speed_corr"]:.3f} | {v["id"]} |')
    (OUT / 'tables.md').write_text('\n'.join(lines) + '\n')
    (OUT / 'summary.json').write_text(json.dumps({str(n): v for n, v in t.items()}, indent=1, default=float) + '\n')
    print('\n'.join(lines[:len(names) + 7]))


if __name__ == '__main__':
    main()
