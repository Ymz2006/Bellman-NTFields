def md(x):
    """HTML prose to Markdown."""
    x = re.sub(r'<strong>(.*?)</strong>', r'**\1**', x, flags=re.S)
    x = re.sub(r'<code>(.*?)</code>', r'`\1`', x, flags=re.S)
    x = re.sub(r'<li>(.*?)</li>', lambda m: '- ' + m.group(1).strip() + '\n', x, flags=re.S)
    x = re.sub(r'</?ul[^>]*>', '\n', x)
    x = re.sub(r'<div class="eq">(.*?)</div>', lambda m: '\n```\n' + re.sub(r'<[^>]+>', '', m.group(1)).replace('&nbsp;', ' ').strip() + '\n```\n', x, flags=re.S)
    x = x.replace('</p>', '\n\n').replace('<p>', '')
    x = re.sub(r'<[^>]+>', '', x)
    return html.unescape(x).strip() + '\n'


def table(head, rows):
    out = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out) + '\n'


